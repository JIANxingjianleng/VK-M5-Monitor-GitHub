GATT_FRESH_SEC = 60.0    # 这么久内做过 UNCACHED 校准，GATT 读数才算实时值（v19：120→60）
CROSS_BATT_KEEP = 300.0  # 跨通道对齐时，另一条通道读数的可信窗口（秒）
                         # 只在这段时间内做「取保守值」；超过就说明那条通道的读数
                         # 已经旧了（比如充完电没再重连蓝牙），不能再压着新值
CROSS_BATT_GAP = 3       # 两通道读数差值达到几个百分点才做对齐（避免抖动）
