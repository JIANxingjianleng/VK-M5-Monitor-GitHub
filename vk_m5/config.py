def dpi_tiers(dpis):
    """返回可显示、可循环的档位数

    只从**尾部**剔除「与前档数值相同」的重复档，例如设备报
    400/800/1200/1600/3200/3200 时返回 5 档（第 6 档与当前档重复，去掉）。

    为什么只截尾：档位索引直接当设备层号用（reader.dpi_set(index)），
    中间去重或整体去重会让 index 与层号错位，切档会写到错误的层。
    尾部截断不改动前 n 个 index 的语义，最安全。
    """
    if not dpis:
        return 0
    n = min(len(dpis), DPI_TIER_MAX)
    while n > 1 and dpis[n - 1] == dpis[n - 2]:
        n -= 1
    return n
